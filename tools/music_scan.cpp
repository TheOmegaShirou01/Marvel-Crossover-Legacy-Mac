// music_scan: builds Music\catalog.tsv for the menu music player.
//
// The soundtrack rips include PlayStation XA streams padded with long silence, and some
// files hold several songs back to back. This decodes every MP3 under the Music folder
// with Windows Media Foundation, measures loudness in 50 ms windows, and writes one line
// per stretch of music (split at >= 2.5 s of silence, shorter than 25 s dropped):
//
//   game <TAB> relative/path.mp3 <TAB> startMs <TAB> endMs <TAB> display name
//
// Build (VS 2022 x64 prompt):  cl /nologo /std:c++17 /EHsc /O2 tools\music_scan.cpp
// Run:                         music_scan.exe <Music folder>
#include <windows.h>
#include <mfapi.h>
#include <mfidl.h>
#include <mfreadwrite.h>
#include <wrl/client.h>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <string>
#include <vector>
#pragma comment(lib,"mfplat.lib")
#pragma comment(lib,"mfreadwrite.lib")
#pragma comment(lib,"mfuuid.lib")
#pragma comment(lib,"ole32.lib")
using Microsoft::WRL::ComPtr;
namespace fs=std::filesystem;

constexpr int kWindowMs=50;
constexpr double kSilenceDb=-48.0;   // quieter than this counts as silence
constexpr int kGapMs=2500;           // silence this long ends a piece
constexpr int kMinPieceMs=25000;     // shorter pieces are jingles, not menu music

// Loudness (dBFS) per 50 ms window, mono-mixed. Empty on failure.
std::vector<float> loudness(const fs::path& file){
 std::vector<float> out;
 ComPtr<IMFSourceReader> r;
 if(FAILED(MFCreateSourceReaderFromURL(file.c_str(),nullptr,&r)))return out;
 const DWORD audio=static_cast<DWORD>(MF_SOURCE_READER_FIRST_AUDIO_STREAM);
 ComPtr<IMFMediaType> t;MFCreateMediaType(&t);
 t->SetGUID(MF_MT_MAJOR_TYPE,MFMediaType_Audio);t->SetGUID(MF_MT_SUBTYPE,MFAudioFormat_PCM);
 t->SetUINT32(MF_MT_AUDIO_BITS_PER_SAMPLE,16);
 if(FAILED(r->SetCurrentMediaType(audio,nullptr,t.Get())))return out;
 ComPtr<IMFMediaType> actual;r->GetCurrentMediaType(audio,&actual);
 UINT32 rate=44100,ch=2;actual->GetUINT32(MF_MT_AUDIO_SAMPLES_PER_SECOND,&rate);actual->GetUINT32(MF_MT_AUDIO_NUM_CHANNELS,&ch);
 const size_t perWin=static_cast<size_t>(rate)*kWindowMs/1000;
 double acc=0;size_t n=0;
 for(;;){
  DWORD flags=0;ComPtr<IMFSample> s;
  if(FAILED(r->ReadSample(audio,0,nullptr,&flags,nullptr,&s))||(flags&MF_SOURCE_READERF_ENDOFSTREAM))break;
  if(!s)continue;
  ComPtr<IMFMediaBuffer> b;if(FAILED(s->ConvertToContiguousBuffer(&b)))continue;
  BYTE* p=nullptr;DWORD len=0;if(FAILED(b->Lock(&p,nullptr,&len)))continue;
  const int16_t* pcm=reinterpret_cast<const int16_t*>(p);
  const size_t frames=len/2/ch;
  for(size_t f=0;f<frames;++f){
   double m=0;for(UINT32 c=0;c<ch;++c)m+=pcm[f*ch+c];m/=ch*32768.0;
   acc+=m*m;
   if(++n==perWin){out.push_back(static_cast<float>(10*std::log10(acc/n+1e-12)));acc=0;n=0;}
  }
  b->Unlock();
 }
 return out;
}
std::string utf8(const std::wstring& w){
 int n=WideCharToMultiByte(CP_UTF8,0,w.c_str(),-1,nullptr,0,nullptr,nullptr);
 std::string s(static_cast<size_t>(n>0?n-1:0),'\0');
 if(n>1)WideCharToMultiByte(CP_UTF8,0,w.c_str(),-1,s.data(),n,nullptr,nullptr);
 return s;
}
int wmain(int argc,wchar_t** argv){
 if(argc<2){std::fwprintf(stderr,L"usage: music_scan <Music folder>\n");return 2;}
 const fs::path root=argv[1];
 CoInitializeEx(nullptr,COINIT_MULTITHREADED);MFStartup(MF_VERSION,MFSTARTUP_LITE);
 std::ofstream cat(root/"catalog.tsv",std::ios::binary|std::ios::trunc);
 cat<<"# game\tpath\tstartMs\tendMs\tname  (generated by tools/music_scan.cpp)\n";
 int files=0,pieces=0;
 for(const auto& e:fs::recursive_directory_iterator(root)){
  if(!e.is_regular_file()||e.path().extension()!=L".mp3")continue;
  const auto rel=fs::relative(e.path(),root);
  const std::string game=utf8(rel.begin()->wstring());
  const auto db=loudness(e.path());++files;
  if(db.empty()){std::printf("  ! could not decode %s\n",utf8(rel.wstring()).c_str());continue;}
  // Split into loud stretches separated by long silence.
  int start=-1,lastLoud=-1;std::vector<std::pair<int,int>> segs;
  for(int i=0;i<static_cast<int>(db.size());++i){
   if(db[static_cast<size_t>(i)]>kSilenceDb){if(start<0)start=i;lastLoud=i;}
   else if(start>=0&&(i-lastLoud)*kWindowMs>=kGapMs){segs.push_back({start,lastLoud});start=-1;}
  }
  if(start>=0)segs.push_back({start,lastLoud});
  std::wstring stem=e.path().stem().wstring();
  int k=0;
  for(const auto& [a,b]:segs){
   const int s=a*kWindowMs,en=(b+1)*kWindowMs;
   if(en-s<kMinPieceMs)continue;
   ++k;++pieces;
   std::string name=utf8(stem);if(segs.size()>1)name+=" (part "+std::to_string(k)+")";
   std::string path=utf8(rel.generic_wstring());
   cat<<game<<'\t'<<path<<'\t'<<s<<'\t'<<en<<'\t'<<name<<'\n';
  }
 }
 MFShutdown();CoUninitialize();
 std::printf("scanned %d files, wrote %d music pieces to catalog.tsv\n",files,pieces);
 return 0;
}
