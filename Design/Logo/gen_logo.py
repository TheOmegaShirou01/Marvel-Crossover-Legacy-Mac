    outer_burst = star(800, 390, 650, 300, 430, 170, 16, -math.pi / 2 + 0.1, jit)
    inner_burst = star(800, 390, 560, 250, 400, 150, 16, -math.pi / 2 + 0.17, jit[::-1])

    glints = []
    # Sparkle glints removed at the user's request (2026-11-19); add (x, y, radius) tuples to bring them back.
    for gx, gy, r in []:
        glints.append(
            f'<path d="M{gx},{gy - r} L{gx + r * 0.16},{gy - r * 0.16} L{gx + r},{gy} L{gx + r * 0.16},{gy + r * 0.16} '
            f'L{gx},{gy + r} L{gx - r * 0.16},{gy + r * 0.16} L{gx - r},{gy} L{gx - r * 0.16},{gy - r * 0.16} Z" '
            f'fill="#fff" filter="url(#glintglow)"/>')

    marvel = word("MARVEL:", CX, 200, 150, 14, "url(#red)", 8, 1.2, 1.6, "#3a0004", "#ff8a8a", 30, 12, "#ffd0d0", "shineS")
    crossover = word("CROSSOVER", CX, 455, 280, 4, "url(#fire)", 16, 1.1, 1.7, "#4a0d00", "#ffb347", 46, 20, "#fffbe0", "shineL")
