"""Generates mcl_logo.svg — Marvel: Crossover Legacy title logo.

Original design built only from SVG shapes, gradients and the Impact system font.
No generated imagery, no third-party artwork. Run:  py -3 gen_logo.py
The animated lightning is NOT part of this file: the app draws it live around the logo
(see lightning_preview.html for the same algorithm in the browser).
"""
import math
import os

W, H = 1600, 760
CX = 800
SKEW = -12


def star(cx, cy, rxo, ryo, rxi, ryi, n, rot, jit):
    pts = []
    for k in range(2 * n):
        a = rot + math.pi * k / n
        if k % 2 == 0:
            j = 1 + jit[k % len(jit)]
            rx, ry = rxo * j, ryo * j
        else:
            rx, ry = rxi, ryi
        pts.append(f"{cx + rx * math.cos(a):.0f},{cy + ry * math.sin(a):.0f}")
    return " ".join(pts)


def word(text, x, y, size, spacing, fill, extrude_steps, extrude_dx, extrude_dy,
         extrude_dark, extrude_light, outer, mid, bevel_top, shine_id):
    """One block-letter word: 3D extrusion, triple outline, gradient face, bevel highlight, shine."""
    t = (f'font-size="{size}" letter-spacing="{spacing}" text-anchor="middle" '
         f'font-family="Impact, \'Arial Black\', sans-serif"')
    out = []
    # Extruded depth (back to front) with a lighter rim on the near edge.
    for i in range(extrude_steps, 0, -1):
        c = extrude_light if i == 1 else extrude_dark
        out.append(f'<text x="{x + extrude_dx * i:.1f}" y="{y + extrude_dy * i:.1f}" {t} fill="{c}" '
                   f'stroke="{c}" stroke-width="{outer}" stroke-linejoin="round">{text}</text>')
    # Outline stack: black / hot rim / black.
    out.append(f'<text x="{x}" y="{y}" {t} fill="none" stroke="#000" stroke-width="{outer}" stroke-linejoin="round">{text}</text>')
    out.append(f'<text x="{x}" y="{y}" {t} fill="none" stroke="url(#rim)" stroke-width="{mid}" stroke-linejoin="round">{text}</text>')
    out.append(f'<text x="{x}" y="{y}" {t} fill="none" stroke="#000" stroke-width="{max(4, mid // 2)}" stroke-linejoin="round">{text}</text>')
    # Face.
    out.append(f'<text x="{x}" y="{y}" {t} fill="{fill}">{text}</text>')
    # Bevel: bright inner edge offset up-left, clipped to the face by drawing it as a thin stroke on top.
    out.append(f'<text x="{x - 2}" y="{y - 3}" {t} fill="none" stroke="{bevel_top}" stroke-width="3" opacity="0.85">{text}</text>')
    # Diagonal shine streak masked to the letters.
    out.append(f'<text x="{x}" y="{y}" {t} fill="url(#{shine_id})">{text}</text>')
    return "\n    ".join(out)


